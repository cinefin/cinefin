def _load_or_create_secret_key() -> str:
    """
    The Django SECRET_KEY: the SECRET_KEY env var when set, otherwise a key
    generated on first run and persisted at CINEFIN_SECRET_KEY_FILE (default
    userdata/.secret_key). It lives with the rest of the runtime data so a
    backup/restore of the userdata dir keeps every session valid. Falls back to
    an ephemeral key — logged loudly — if the path is unwritable.
    """
    from_env = os.environ.get("SECRET_KEY")
    if from_env:
        return from_env
    from django.core.management.utils import get_random_secret_key

    key_file = Path(os.environ.get("CINEFIN_SECRET_KEY_FILE") or os.path.join(CINEFIN_USERDATA_DIR, ".secret_key"))
    try:
        if key_file.exists():
            stored = key_file.read_text().strip()
            if stored:
                return stored
        key_file.parent.mkdir(parents=True, exist_ok=True)
        generated = get_random_secret_key()
        key_file.write_text(generated)
        os.chmod(key_file, 0o600)
        return generated
    except OSError as exc:
        logging.getLogger("cinefin").warning(
            "Could not persist SECRET_KEY at %s (%s) — using an ephemeral key; sessions "
            "will reset every restart. Set the SECRET_KEY env var to a fixed value.",
            key_file,
            exc,
        )
        return get_random_secret_key()


