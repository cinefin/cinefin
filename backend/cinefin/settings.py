# Static serving is WhiteNoise in every deployment. Two deliberate choices so
# a box where `collectstatic` has never run (the systemd runserver deployment)
# cannot break with DEBUG off:
#
# * Non-manifest storage (CompressedStaticFilesStorage). The manifest variant
#   raises for every {% static %} reference missing from staticfiles.json —
#   i.e. 500s on every page when collectstatic never ran. (Note: the old
#   `STATICFILES_STORAGE = ...CompressedManifestStaticFilesStorage` setting
#   was silently ignored on Django >= 5.1 anyway; STORAGES is the supported
#   form, so manifest storage was never actually in effect.)
# * WHITENOISE_USE_FINDERS: serve straight from the app's static/ dirs via the
#   staticfiles finders, so STATIC_ROOT doesn't need to exist at all. Where a
#   collectstatic output does exist (the Docker image builds one) it is still
#   used and compressed as usual.
# * WHITENOISE_AUTOREFRESH: always on. Its default is settings.DEBUG, and with
#   DEBUG off WhiteNoise caches every file's size at startup — a git pull (or
#   any edit) that changes a JS file while the server runs is then served
#   TRUNCATED to its old Content-Length, silently killing that page's script.
#   Per-request stat calls are irrelevant at this app's scale; correctness on
#   pull-based deploys is not.
STORAGES = {
    "default": {"BACKEND": "django.core.files.storage.FileSystemStorage"},
    "staticfiles": {"BACKEND": "whitenoise.storage.CompressedStaticFilesStorage"},
}
WHITENOISE_USE_FINDERS = True
WHITENOISE_AUTOREFRESH = True

